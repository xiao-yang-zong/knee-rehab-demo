const { chromium } = require('playwright');
const fs = require('fs');
const [,, BASE, OUT, FAKE, VIDEO] = process.argv;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
(async () => {
  const b = await chromium.launch({ args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream'] });
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, permissions: ['camera'] });
  const p = await ctx.newPage(); const errs = [];
  p.on('pageerror', (e) => errs.push(String(e))); p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
  await p.route('**/vendor/mediapipe/pose/pose.js', (r) => r.fulfill({ contentType: 'application/javascript', body: fs.readFileSync(FAKE, 'utf8') }));
  await p.route('**/config/exercises.json', async (r) => { const res = await r.fetch(); const d = await res.json(); d.exercises.forEach((e) => { if (e.holdSec) e.holdSec = 1; e.reps = 3; }); r.fulfill({ contentType: 'application/json', body: JSON.stringify(d) }); });
  const R = {};
  await p.goto(BASE + '/'); await p.waitForSelector('#welcome-go');
  await p.click('label:has(#consent-tool)'); await p.click('label:has(#consent-doctor)'); await p.click('#welcome-go');
  await p.click('#setup-skip'); await p.click('#today-start');
  await p.waitForSelector('#check-layer.open'); await p.click('#check-go');
  await p.waitForSelector('[data-screen="prep"]:not([hidden])'); await sleep(700);
  await p.screenshot({ path: `${OUT}/v9-prep.png`, fullPage: false });
  await p.evaluate(() => window.scrollTo(0, 2000)); await sleep(400);
  await p.screenshot({ path: `${OUT}/v9-prep-bottom.png` });
  R.posture = await p.textContent('#prep-steps');
  R.camera = await p.textContent('#prep-camera');
  // 1) 后置摄像头
  await p.click('#prep-cam button[data-value="environment"]'); await sleep(300);
  R.camNoteVisible = await p.$eval('#prep-cam-note', (e) => !e.hidden);
  await p.screenshot({ path: `${OUT}/v9-prep-rear.png` });
  await p.evaluate(() => { window.__FAKE_MODE = 'ext'; });
  await p.click('#start-btn');
  await p.waitForSelector('[data-screen="session"]:not([hidden])', { timeout: 30000 });
  R.rearNoMirror = await p.$eval('#stage', (e) => e.classList.contains('no-mirror'));
  await p.waitForSelector('[data-screen="after"]:not([hidden])', { timeout: 40000 });
  R.rearAfter = await p.textContent('#after-summary');
  await p.click('#faces .face-btn[data-level="green"]'); await p.click('#after-next');
  // 2) 演示模式（视频文件）：下一个动作足跟滑动
  await p.waitForSelector('[data-screen="prep"]:not([hidden])');
  await p.evaluate(() => { window.__FAKE_MODE = 'heel'; });
  await p.setInputFiles('#demo-file', VIDEO);
  await p.waitForSelector('[data-screen="session"]:not([hidden])', { timeout: 30000 });
  await sleep(2500);
  R.demoSub = await p.textContent('#hud-sub');
  R.demoNoMirror = await p.$eval('#stage', (e) => e.classList.contains('no-mirror'));
  await p.screenshot({ path: `${OUT}/v9-demo-session.png` });
  await p.waitForSelector('[data-screen="after"]:not([hidden])', { timeout: 60000 });
  R.demoAfter = await p.textContent('#after-summary');
  await p.click('#faces .face-btn[data-level="green"]');
  await p.goto(BASE + '/#records'); await p.waitForSelector('[data-screen="records"]:not([hidden])'); await sleep(500);
  R.history = await p.$$eval('#rec-history .row', (rs) => rs.map((r) => r.innerText.replace(/\n/g, ' ')));
  await p.screenshot({ path: `${OUT}/v9-records.png`, fullPage: true });
  R.errors = errs;
  console.log(JSON.stringify(R, null, 2)); await b.close();
})().catch((e) => { console.error('FAILED', e.message); process.exit(1); });
